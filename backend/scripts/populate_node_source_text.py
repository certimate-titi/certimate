def main():
    settings = get_settings()
    engine = create_engine(settings.DATABASE_URL)
    Session = sessionmaker(bind=engine)
    session = Session()

    # Get all nodes without source_text
    nodes = session.execute(text(
        "SELECT id, name FROM knowledge_nodes WHERE source_text IS NULL OR source_text = ''"
    )).fetchall()

    updated = 0
    skipped = 0

    for node_id, node_name in nodes:
        desc = NODE_DESCRIPTIONS.get(node_name)
        if desc:
            source_text = f"# {node_name}\n\n{desc}"
            session.execute(text(
                "UPDATE knowledge_nodes SET source_text = :text WHERE id = :id"
            ), {"text": source_text, "id": node_id})
            updated += 1
        else:
            # Fallback: generate a simple description
            source_text = f"# {node_name}\n\n此考點涵蓋「{node_name}」的核心知識與考試重點。\n\n> 提示：可透過右側 AI 教練深入了解此考點的細節。"
            session.execute(text(
                "UPDATE knowledge_nodes SET source_text = :text WHERE id = :id"
            ), {"text": source_text, "id": node_id})
            updated += 1

    session.commit()
    session.close()
    print(f"✅ 更新 {updated} 個節點的 source_text（跳過 {skipped} 個）")


if __name__ == "__main__":
    main()
